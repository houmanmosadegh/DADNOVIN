import { chromium } from '@playwright/test'
const EXE = '/home/holirex/.cache/puppeteer/chrome-headless-shell/linux-155.0.8059.84/chrome-headless-shell-linux64/chrome-headless-shell'
const b = await chromium.launch({ executablePath: EXE, args: ['--no-sandbox'] })
const p = await b.newPage({ viewport: { width: 390, height: 844 } })
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle' })
await p.waitForTimeout(1600)
await p.screenshot({ path: '/tmp/qa/mob-hero.png' })
for (const [y, n] of [[1100, 'mob-about'], [2300, 'mob-pic'], [3400, 'mob-svc'], [5200, 'mob-team'], [7000, 'mob-cta']]) {
  await p.evaluate((v) => window.scrollTo(0, v), y)
  await p.waitForTimeout(450)
  await p.screenshot({ path: `/tmp/qa/${n}.png` })
}
const a = await b.newPage({ viewport: { width: 390, height: 844 } })
await a.goto('http://localhost:5173/about', { waitUntil: 'networkidle' })
await a.waitForTimeout(1300)
await a.evaluate(() => window.scrollTo(0, 950))
await a.waitForTimeout(450)
await a.screenshot({ path: '/tmp/qa/mob-rcard.png' })
const s = await b.newPage({ viewport: { width: 390, height: 844 } })
await s.goto('http://localhost:5173/services', { waitUntil: 'networkidle' })
await s.waitForTimeout(1300)
await s.evaluate(() => window.scrollTo(0, 900))
await s.waitForTimeout(450)
await s.screenshot({ path: '/tmp/qa/mob-services.png' })
await b.close()
console.log('ok')
