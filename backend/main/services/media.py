"""Media pipeline: signature validation → re-encode → organized storage."""

import io
import uuid
from pathlib import Path

from fastapi import HTTPException, UploadFile
from PIL import Image
from sqlalchemy.ext.asyncio import AsyncSession

from ..core.config import get_settings
from ..models.media import MediaAsset
from ..models.user import User

ALLOWED_TYPES = {
    "image/jpeg": "jpg",
    "image/png": "png",
    "image/webp": "webp",
}
# magic-byte signatures we verify ourselves — the declared MIME is not trusted
_SIGNATURES = {
    "image/jpeg": [b"\xff\xd8\xff"],
    "image/png": [b"\x89PNG\r\n\x1a\n"],
    "image/webp": [b"RIFF"],
}


def storage_root() -> Path:
    root = Path(get_settings().storage_dir) / "media"
    root.mkdir(parents=True, exist_ok=True)
    return root


def _sniff(data: bytes) -> str | None:
    for mime, sigs in _SIGNATURES.items():
        for sig in sigs:
            if data.startswith(sig):
                if mime == "image/webp" and data[8:12] != b"WEBP":
                    continue
                return mime
    return None


async def store_upload(
    db: AsyncSession, upload: UploadFile, actor: User | None, alt: str = ""
) -> MediaAsset:
    settings = get_settings()
    raw = await upload.read()
    if not raw:
        raise HTTPException(400, {"code": "empty_file", "message": "فایل خالی است."})
    if len(raw) > settings.media_max_bytes:
        raise HTTPException(
            413,
            {"code": "file_too_large", "message": "حجم فایل بیش از حد مجاز است."},
        )
    declared = (upload.content_type or "").split(";")[0].strip().lower()
    sniffed = _sniff(raw)
    if sniffed is None or sniffed not in ALLOWED_TYPES:
        raise HTTPException(
            415,
            {"code": "bad_type", "message": "فقط تصویر JPG/PNG/WebP قابل قبول است."},
        )
    if declared and declared != sniffed:
        raise HTTPException(
            415,
            {"code": "type_mismatch", "message": "نوع فایل با محتوای آن ناسازگار است."},
        )

    # decode + re-encode — strips polyglot payloads and oversized dimensions
    try:
        img = Image.open(io.BytesIO(raw))
        img.load()
    except Exception:
        raise HTTPException(
            415, {"code": "corrupt", "message": "فایل تصویر خراب است."}
        ) from None
    if img.mode in ("P", "CMYK", "LA", "I;16"):
        img = img.convert("RGB")
    elif img.mode == "RGBA":
        # keep alpha for png/webp
        pass
    elif img.mode != "RGB":
        img = img.convert("RGB")

    max_px = settings.media_max_pixels
    if max(img.size) > max_px:
        ratio = max_px / max(img.size)
        img = img.resize(
            (max(1, round(img.width * ratio)), max(1, round(img.height * ratio))),
            Image.LANCZOS,
        )

    stored_name = f"{uuid.uuid4().hex}.{sniffed.split('/')[1].replace('jpeg', 'jpg')}"
    out = storage_root() / stored_name
    if sniffed == "image/jpeg":
        img.save(out, "JPEG", quality=86, optimize=True)
    elif sniffed == "image/png":
        img.save(out, "PNG", optimize=True)
    else:
        img.save(out, "WEBP", quality=88)

    asset = MediaAsset(
        stored_name=stored_name,
        original_name=(upload.filename or "")[:255],
        content_type=sniffed,
        size_bytes=out.stat().st_size,
        width=img.width,
        height=img.height,
        alt=alt[:255],
        uploaded_by=actor.id if actor else None,
    )
    db.add(asset)
    await db.flush()
    return asset


def media_path(asset: MediaAsset) -> Path:
    # stored_name is generated by us (hex + fixed ext) — never user-controlled
    return storage_root() / asset.stored_name


async def delete_asset(db: AsyncSession, asset: MediaAsset) -> None:
    path = media_path(asset)
    await db.delete(asset)
    await db.flush()
    try:
        path.unlink(missing_ok=True)
    except OSError:
        pass
